#!/usr/bin/env python3
"""Generate ~/.config/hypr/kidlock.lua from the admin config file.

Reads a simple KEY=VALUE config (config/kidlock.conf) and emits a Hyprland
Lua snippet that defines the `kidlock` submap. Every bind in that submap
swallows its key combo with the `no_op` dispatcher, so the compositor
consumes the combo and the focused app never receives it.

Keys NOT listed here (plain letters, digits, space, enter, backspace,
delete, punctuation, and Shift used for normal typing) are never bound, so
they keep flowing to the focused app untouched.

Usage:
    generate_lua.py [--config PATH] [--output PATH]

No third-party dependencies; stdlib only.
"""

import argparse
import os
import sys

# --------------------------------------------------------------------------
# Key tables. Names are XKB keysyms as understood by Hyprland's Lua API
# (validated live against `hyprctl binds` on Hyprland 0.56 / Omarchy 4).
# --------------------------------------------------------------------------

LETTERS = [chr(c) for c in range(ord("A"), ord("Z") + 1)]
DIGITS = [str(d) for d in range(0, 10)]
FKEYS = ["F%d" % n for n in range(1, 13)]

# Punctuation / symbol keys (unshifted XKB names; shifted variants come free
# because bare Shift is never bound, so Shift+key still reaches the client).
PUNCT = [
    "minus", "equal", "bracketleft", "bracketright", "backslash",
    "semicolon", "apostrophe", "grave", "comma", "period", "slash",
]

# Special keys that are dangerous as *modifier combos* (always swallowed).
COMBO_SPECIAL = [
    "Escape", "Tab", "Return", "BackSpace", "Delete", "Insert",
    "Home", "End", "Prior", "Next", "Left", "Right", "Up", "Down",
    "Print", "Pause", "Menu", "SPACE",
]

# Modifier groups whose combos are swallowed wholesale. NOTE: plain SHIFT is
# deliberately absent -- Shift+letter/punctuation must keep working for
# normal typing (uppercase, symbols).
MOD_GROUPS = [
    "CTRL",
    "ALT",
    "SUPER",
    "CTRL + ALT",
    "CTRL + SHIFT",
    "ALT + SHIFT",
    "SUPER + SHIFT",
    "CTRL + SUPER",
    "ALT + SUPER",
    "CTRL + ALT + SHIFT",
]

# Bare (modifier-free) keys swallowed when locked, gated by config flags.
BARE_GROUPS = {
    # config flag       keys
    "BLOCK_ESC":    ["Escape"],
    "BLOCK_TAB":    ["Tab", "SHIFT + Tab"],
    "BLOCK_ARROWS": ["Up", "Down", "Left", "Right",
                     "SHIFT + Up", "SHIFT + Down", "SHIFT + Left", "SHIFT + Right"],
    "BLOCK_NAV":    ["Home", "End", "Prior", "Next", "Insert"],
    "BLOCK_FKEYS":  list(FKEYS),
    "BLOCK_SYS":    ["Print", "Pause", "Scroll_Lock", "Menu", "Super_L", "Super_R"],
}

# Super+Super_L/R validated live; other mod+modkey combos go through pcall
# protection in the emitted Lua anyway.
MOD_MODKEYS = ["SUPER + Super_L", "SUPER + Super_R"]

DEFAULTS = {
    "BLOCK_ESC": "true",
    "BLOCK_TAB": "true",
    "BLOCK_ARROWS": "true",
    "BLOCK_NAV": "true",
    "BLOCK_FKEYS": "true",
    "BLOCK_SYS": "true",
}


def load_conf(path):
    """Parse a minimal KEY=VALUE file (ignores blanks and # comments)."""
    conf = dict(DEFAULTS)
    if not path or not os.path.exists(path):
        return conf
    with open(path, "r", encoding="utf-8") as fh:
        for line in fh:
            line = line.strip()
            if not line or line.startswith("#") or "=" not in line:
                continue
            key, _, value = line.partition("=")
            key, value = key.strip(), value.strip().strip("\"'")
            if key:
                conf[key] = value
    return conf


def truthy(value):
    return str(value).strip().lower() in ("1", "true", "yes", "on")


def lua_string_list(items):
    return "{ " + ", ".join('"%s"' % i for i in items) + " }"


def generate(conf):
    mod_keys = LETTERS + DIGITS + FKEYS + PUNCT + COMBO_SPECIAL
    lines = []
    a = lines.append
    a("-- GENERATED by kidlock's generate_lua.py -- DO NOT EDIT BY HAND.")
    a("-- Regenerate with:  kidlock apply-config")
    a("-- Source: config/kidlock.conf (BLOCK_* flags).")
    a("")
    a("-- This module defines the `kidlock` submap used by `kidlock lock`.")
    a("-- While Hyprland sits in this submap:")
    a("--   * every bind below swallows its combo via no_op (client never sees it)")
    a("--   * all default compositor binds are inactive (workspace/window mgmt dead)")
    a("--   * anything NOT bound (plain typing keys, mouse) works normally")
    a("-- Unlocking is just:  hl.dispatch(hl.dsp.submap(\"reset\"))")
    a("-- NOTE: the 2-argument define_submap form (no reset string) is REQUIRED:")
    a("-- passing \"reset\" as 2nd arg makes Hyprland exit the submap on the first")
    a("-- unmatched keypress (verified live), which would unlock on plain typing.")
    a("")
    a("local KIDLOCK_MODS = " + lua_string_list(MOD_GROUPS))
    a("local KIDLOCK_MOD_KEYS = " + lua_string_list(mod_keys))
    a("local KIDLOCK_MOD_MODKEYS = " + lua_string_list(MOD_MODKEYS))
    a("local KIDLOCK_BARE = " + lua_string_list(
        [k for flag, keys in sorted(BARE_GROUPS.items())
         if truthy(conf.get(flag, "true")) for k in keys]))
    a("")
    a("hl.define_submap(\"kidlock\", function()")
    a("  local noop = hl.dsp.no_op()")
    a("  local count, failed = 0, 0")
    a("  -- pcall: one bad key name must never abort the whole submap.")
    a("  local function swallow(spec)")
    a("    local ok = pcall(hl.bind, spec, noop,")
    a("      { description = \"kidlock: swallow \" .. spec })")
    a("    if ok then count = count + 1 else failed = failed + 1 end")
    a("  end")
    a("  for _, mod in ipairs(KIDLOCK_MODS) do")
    a("    for _, key in ipairs(KIDLOCK_MOD_KEYS) do")
    a("      swallow(mod .. \" + \" .. key)")
    a("    end")
    a("  end")
    a("  for _, spec in ipairs(KIDLOCK_MOD_MODKEYS) do swallow(spec) end")
    a("  for _, spec in ipairs(KIDLOCK_BARE) do swallow(spec) end")
    a("end)")
    a("")
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description="Generate kidlock.lua for Hyprland.")
    ap.add_argument("--config", default=os.path.expanduser("~/.config/kidlock/kidlock.conf"))
    ap.add_argument("--output", default=os.path.expanduser("~/.config/hypr/kidlock.lua"))
    ap.add_argument("--stdout", action="store_true", help="Print to stdout instead of writing.")
    args = ap.parse_args()

    conf = load_conf(args.config)
    text = generate(conf)

    # Report what the config selected (useful, deterministic).
    bare_total = sum(
        len(keys) for flag, keys in BARE_GROUPS.items()
        if truthy(conf.get(flag, "true")))
    combo_total = len(MOD_GROUPS) * (len(LETTERS + DIGITS + FKEYS + PUNCT + COMBO_SPECIAL))
    print("kidlock: %d modifier-combo swallows + %d bare-key swallows (+%d mod-modkeys)"
          % (combo_total, bare_total, len(MOD_MODKEYS)))

    if args.stdout:
        sys.stdout.write(text)
        return 0
    with open(args.output, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("kidlock: wrote %s" % args.output)
    return 0


if __name__ == "__main__":
    sys.exit(main())
